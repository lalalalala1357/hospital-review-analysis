def run_lazy_import():
    # ==========================================
    # 💾 將內建獎項清單寫入 SQLite，重複資料自動略過
    # ==========================================
    print("🚀 啟動滿血版一鍵匯入模式...")
    success_count = 0
    duplicate_count = 0
    
    try:
        with sqlite3.connect(HR_DB) as conn:
            cursor = conn.cursor()
            for h_name, dept, award in awards_data:
                try:
                    cursor.execute('''
                        INSERT INTO hospital_awards (hospital_name, department, award_name) 
                        VALUES (?, ?, ?)
                    ''', (h_name, dept, award))
                    success_count += 1
                except sqlite3.IntegrityError:
                    duplicate_count += 1
            conn.commit()
            
        print(f"🎉 魔法施展完畢！")
        print(f"✅ 成功新增：{success_count} 筆權威紀錄！")
        if duplicate_count > 0:
            print(f"⏭️ 略過重複：{duplicate_count} 筆 (你之前匯入過的已自動跳過)")
        print("👉 趕快去網頁看「科別排行」，現在每個科別都有超多神仙打架了！")
        
    except Exception as e:
        print(f"❌ 發生錯誤: {e}")

if __name__ == "__main__":
    run_lazy_import()
